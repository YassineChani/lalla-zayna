window.I18N = {
  currentLang: 'fr',
  translations,

  setLanguage(lang) {
    if (!this.translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('lz_lang', lang);
    document.documentElement.lang = lang;
    this.applyTranslations();
  },

  get(path) {
    const keys = path.split('.');
    let obj = this.translations[this.currentLang] || this.translations.fr;
    for (const key of keys) {
      if (obj && obj[key] !== undefined) {
        obj = obj[key];
      } else {
        return path;
      }
    }
    return obj;
  },

  applyTranslations() {
    // Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.get(key);
      if (typeof val === 'string') {
        el.innerHTML = val;
      }
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const val = this.get(key);
      if (typeof val === 'string') {
        el.setAttribute('placeholder', val);
      }
    });

    // Update active state in language selector
    document.querySelectorAll('.lang-btn').forEach(btn => {
      if (btn.getAttribute('data-lang') === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });

    // Dispatch custom event for dynamic components like products list
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: this.currentLang } }));
  },

  init() {
    const saved = localStorage.getItem('lz_lang');
    if (saved && this.translations[saved]) {
      this.currentLang = saved;
    }
    document.documentElement.lang = this.currentLang;
  }
};
